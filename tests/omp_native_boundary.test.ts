test("later sources are rechecked after an earlier writer callback returns", async () => {
  const ws = workspace({ "one.txt": "alpha\n", "two.txt": "beta\n" });
  const input = `[one.txt#${ws.tag("one.txt")}]\nPUT 1:\n+ALPHA\n[two.txt#${ws.tag("two.txt")}]\nPUT 1:\n+BETA`;
  const result = await ws.session(input).apply({ lspFlush: false },
    async (error: Error | null, request: any) => {
      const response = await ws.writer(error, request);
      if (request.path.endsWith("one.txt")) writeFileSync(join(ws.root, "two.txt"), "external\n");
      return response;
    }, async (_error: Error | null, batch: any) => approve(batch));
  expect(result.isError).toBe(true);
  expect(ws.written.map(request => request.path)).toEqual([join(ws.root, "one.txt")]);
  expect(readFileSync(join(ws.root, "two.txt"), "utf8")).toBe("external\n");
});

test("approved noops retain the native repeated-noop escalation", async () => {
  const ws = workspace({ "one.txt": "alpha\n" });
  const input = `[one.txt#${ws.tag("one.txt")}]\nPUT 1:\n+alpha`;
  const outcomes = [];
  for (let attempt = 0; attempt < 3; attempt++) {
    outcomes.push(await ws.session(input).apply({ lspFlush: false }, ws.writer,
      async (_error: Error | null, batch: any) => approve(batch)));
  }
  expect(outcomes[0].isError).toBe(false);
  expect(outcomes[1].isError).toBe(false);
  expect(outcomes[2].isError).toBe(true);
  expect(outcomes[2].text).toContain("STOP");
  expect(ws.written).toEqual([]);
  expect(readFileSync(join(ws.root, "one.txt"), "utf8")).toBe("alpha\n");
});

