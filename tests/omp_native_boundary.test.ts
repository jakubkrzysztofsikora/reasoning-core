test("OS failure retains and reports the actual landed prefix through writer observations", async () => {
  const ws = workspace({ "one.txt": "alpha\n", "two.txt": "beta\n" });
  const one = ws.tag("one.txt"), two = ws.tag("two.txt");
  const input = `[one.txt#${one}]\nPUT 1:\n+ALPHA\n[two.txt#${two}]\nPUT 1:\n+BETA`;
  let calls = 0;
  const result = await ws.session(input).apply({ lspFlush: false },
    async (error: Error | null, request: any) => {
      if (request.path.endsWith("two.txt")) throw new Error("OS write failure");
      return ws.writer(error, request);
    }, async (_error: Error | null, batch: any) => { calls++; return approve(batch); });
  expect(calls).toBe(1);
  expect(result.isError).toBe(true);
  expect(result.text).toContain("OS write failure");
  expect(ws.written.map(request => request.path)).toEqual([join(ws.root, "one.txt")]);
  expect(readFileSync(join(ws.root, "one.txt"), "utf8")).toBe("ALPHA\n");
  expect(readFileSync(join(ws.root, "two.txt"), "utf8")).toBe("beta\n");
  expect(ws.store.headText(join(ws.root, "one.txt"))).toBe("ALPHA\n");
  expect(ws.store.headHash(join(ws.root, "two.txt"))).toBe(two);
});

