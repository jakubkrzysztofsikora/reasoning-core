test("a later parent symlink change is rejected after the earlier writer returns", async () => {
  const ws = workspace({ "one.txt": "alpha\n" });
  mkdirSync(join(ws.root, "first"));
  mkdirSync(join(ws.root, "second"));
  writeFileSync(join(ws.root, "first", "two.txt"), "beta\n");
  writeFileSync(join(ws.root, "second", "two.txt"), "beta\n");
  symlinkSync(join(ws.root, "first"), join(ws.root, "alias"));
  const tag = ws.store.recordSnapshot(join(ws.root, "alias", "two.txt"), "beta\n");
  const input = `[one.txt#${ws.tag("one.txt")}]\nPUT 1:\n+ALPHA\n[alias/two.txt#${tag}]\nPUT 1:\n+BETA`;
  const result = await ws.session(input).apply({ lspFlush: false },
    async (error: Error | null, request: any) => {
      const response = await ws.writer(error, request);
      if (request.path.endsWith("one.txt")) {
        unlinkSync(join(ws.root, "alias"));
        symlinkSync(join(ws.root, "second"), join(ws.root, "alias"));
      }
      return response;
    }, async (_error: Error | null, batch: any) => approve(batch));
  expect(result.isError).toBe(true);
  expect(ws.written.map(request => request.path)).toEqual([join(ws.root, "one.txt")]);
  expect(readFileSync(join(ws.root, "first", "two.txt"), "utf8")).toBe("beta\n");
  expect(readFileSync(join(ws.root, "second", "two.txt"), "utf8")).toBe("beta\n");
});
