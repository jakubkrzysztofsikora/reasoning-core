import { afterEach, expect, test } from "bun:test";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, realpathSync, rmSync, unlinkSync, writeFileSync, mkdirSync, symlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { createRequire } from "node:module";
import { join } from "node:path";

// Exercise the real native engine, including its snapshot/register store.
const modulePath = process.env.RC_OMP_NATIVE_MODULE ??
  "@oh-my-pi/pi-natives";
const native = modulePath.endsWith(".node") ? createRequire(import.meta.url)(modulePath) : await import(modulePath);
const roots: string[] = [];
afterEach(() => { for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true }); });
const sha = (text: string) => createHash("sha256").update(text).digest("hex");
function workspace(files: Record<string, string>) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "rc native boundary ")));
  roots.push(root);
  for (const [path, text] of Object.entries(files)) writeFileSync(join(root, path), text);
  const store = new native.EditStore();
  const tag = (path: string, text = files[path]) => store.recordSnapshot(join(root, path), text);
  const session = (input: string) => {
    const value = new native.EditSession(store, {
      cwd: root, homeDir: root, mode: "hashline", allowFuzzy: false,
      fuzzyThreshold: 0.95, enforceSeenLines: false, rawInput: false,
      blockAutoGenerated: true, planActive: false, planWritableRoots: [],
      urlSchemes: [], urlAliasSchemes: [],
    });
    value.setArgsJson(JSON.stringify({ input }));
    value.finish();
    return value;
  };
  const written: any[] = [];
  const writer = async (error: Error | null, request: any) => {
    if (error) throw error;
    written.push(request);
    if (request.op === "delete") unlinkSync(request.path);
    else {
      writeFileSync(request.moveTo ?? request.path, request.content);
      if (request.moveTo) unlinkSync(request.path);
    }
    return { written: request.content ?? "" };
  };
  return { root, store, tag, session, written, writer };
}
function candidate(path: string, before: string | null, after: string | null) {
  return { path, operation: after === null ? "delete" : "write", beforeSrc: before,
    afterSrc: after, expectedBeforeSha256: before === null ? null : sha(before) };
}
function approve(batch: any) {
  return { allowed: true, finalInputSha256: batch.finalInputSha256 };
}

test("complete multi-file candidates are approved before the first write; denied last member changes no files or snapshots", async () => {
  const ws = workspace({ "one.txt": "alpha\n", "two.txt": "beta\n" });
  const one = ws.tag("one.txt"), two = ws.tag("two.txt");
  const input = `[one.txt#${one}]\nPUT 1:\n+ALPHA\n[two.txt#${two}]\nPUT 1:\n+BETA`;
  let calls = 0;
  const result = await ws.session(input).apply({ lspFlush: false }, ws.writer,
    async (error: Error | null, batch: any) => {
      if (error) throw error;
      calls++;
      expect(ws.written).toEqual([]);
      expect(batch.finalInputSha256).toBe(sha(JSON.stringify({ input })));
      expect(batch.candidates).toEqual([
        candidate(join(ws.root, "one.txt"), "alpha\n", "ALPHA\n"),
        candidate(join(ws.root, "two.txt"), "beta\n", "BETA\n"),
      ]);
      return { allowed: false, finalInputSha256: batch.finalInputSha256 };
    });
  expect(calls).toBe(1);
  expect(result.isError).toBe(true);
  expect(ws.written).toEqual([]);
  expect(readFileSync(join(ws.root, "one.txt"), "utf8")).toBe("alpha\n");
  expect(readFileSync(join(ws.root, "two.txt"), "utf8")).toBe("beta\n");
  expect(ws.store.headHash(join(ws.root, "one.txt"))).toBe(one);
  expect(ws.store.headHash(join(ws.root, "two.txt"))).toBe(two);
});

test("approved candidates match persisted bytes", async () => {
  const ws = workspace({ "one.txt": "alpha\r\n" });
  const input = `[one.txt#${ws.tag("one.txt")}]\nPUT 1:\n+ALPHA`;
  let prepared: any;
  const result = await ws.session(input).apply({ lspFlush: false }, ws.writer,
    async (_error: Error | null, batch: any) => { prepared = batch; return approve(batch); });
  expect(prepared?.candidates).toEqual([candidate(join(ws.root, "one.txt"), "alpha\r\n", "ALPHA\r\n")]);
  expect(result.isError).toBe(false);
  expect(readFileSync(join(ws.root, "one.txt"), "utf8")).toBe("ALPHA\r\n");
});

test("moves include source deletion and absent destination; delete is complete", async () => {
  const ws = workspace({ "one.txt": "alpha\n", "old.txt": "old\n" });
  const input = `[one.txt#${ws.tag("one.txt")}]\nMV moved.txt\n[old.txt#${ws.tag("old.txt")}]\nREM`;
  let prepared: any;
  const result = await ws.session(input).apply({ lspFlush: false }, ws.writer,
    async (_error: Error | null, batch: any) => { prepared = batch; return approve(batch); });
  expect(prepared?.candidates).toEqual([
    candidate(join(ws.root, "one.txt"), "alpha\n", null),
    candidate(join(ws.root, "moved.txt"), null, "alpha\n"),
    candidate(join(ws.root, "old.txt"), "old\n", null),
  ]);
  expect(result.isError).toBe(false);
  expect(existsSync(join(ws.root, "one.txt"))).toBe(false);
  expect(existsSync(join(ws.root, "old.txt"))).toBe(false);
  expect(readFileSync(join(ws.root, "moved.txt"), "utf8")).toBe("alpha\n");
});

test("persistent registers are published only after approved writes", async () => {
  const ws = workspace({ "one.txt": "alpha\nbeta\n", "two.txt": "tail\n" });
  const cut = `[one.txt#${ws.tag("one.txt")}]\nCUT 1 @saved`;
  let calls = 0;
  let result = await ws.session(cut).apply({ lspFlush: false }, ws.writer,
    async (_error: Error | null, batch: any) => { calls++; return approve(batch); });
  expect(calls).toBe(1);
  expect(result.isError).toBe(false);
  const paste = `[two.txt#${ws.tag("two.txt")}]\nPUT <1 @saved`;
  let prepared: any;
  result = await ws.session(paste).apply({ lspFlush: false }, ws.writer,
    async (_error: Error | null, batch: any) => { prepared = batch; return approve(batch); });
  expect(prepared?.candidates).toEqual([candidate(join(ws.root, "two.txt"), "tail\n", "alpha\ntail\n")]);
  expect(result.isError).toBe(false);
  expect(readFileSync(join(ws.root, "two.txt"), "utf8")).toBe("alpha\ntail\n");
});

