#!/usr/bin/env bash
#
# daily-benchmark.sh
#
# Run `rc benchmark` once per day and store dated reports so sessions can be
# compared over time. Designed to be driven by a launchd LaunchAgent but safe
# to run by hand.
#
# Outputs:
#   ~/.local/share/reasoning-core/benchmarks/YYYY-MM-DD/
#     benchmark-day.json          metrics for the last 24 h
#     benchmark-day.md            human-readable daily report
#     benchmark-week.json         metrics for the last 7 days
#     benchmark-week.md           human-readable weekly report
#     trend.md                    day-over-day/weekly comparison
#   ~/.local/share/reasoning-core/benchmarks/latest -> today's directory
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RC="${REPO_ROOT}/bin/rc"
DATE="$(date +%Y-%m-%d)"
OUT_ROOT="${HOME}/.local/share/reasoning-core/benchmarks"
OUT_DIR="${OUT_ROOT}/${DATE}"
LATEST_LINK="${OUT_ROOT}/latest"

mkdir -p "${OUT_DIR}"

# Resolve yesterday's directory for trend comparison.
YESTERDAY_DIR="${OUT_ROOT}/$(date -v-1d +%Y-%m-%d 2>/dev/null || date -d 'yesterday' +%Y-%m-%d)"

run_benchmark() {
    local days="$1"
    local json_out="$2"
    local md_out="$3"

    if [[ ! -x "${RC}" ]]; then
        echo "error: rc shim not found at ${RC}" >&2
        exit 1
    fi

    "${RC}" benchmark \
        --days "${days}" \
        --json "${json_out}" \
        --output "${md_out}"
}

echo "[rc-daily-benchmark] date=${DATE} out=${OUT_DIR}"

run_benchmark 1 "${OUT_DIR}/benchmark-day.json" "${OUT_DIR}/benchmark-day.md"
run_benchmark 7 "${OUT_DIR}/benchmark-week.json" "${OUT_DIR}/benchmark-week.md"

# Keep the baseline reference with operational reports. This is context only:
# audit proxies are not causal evidence of quality.
BASELINE_ID="baseline-2026-08-09"
if "${RC}" baseline show "${BASELINE_ID}" > "${OUT_DIR}/baseline-reference.json"; then
    echo "${BASELINE_ID}" > "${OUT_DIR}/baseline-id.txt"
fi

# Build a trend comparison if yesterday exists.
TREND_MD="${OUT_DIR}/trend.md"
{
    echo "# reasoning-core benchmark trend — ${DATE}"
    echo ""
    echo "- Daily report: ${OUT_DIR}/benchmark-day.md"
    echo "- Weekly report: ${OUT_DIR}/benchmark-week.md"
    echo "- Baseline context: ${OUT_DIR}/baseline-reference.json"
    echo ""

    if [[ -f "${YESTERDAY_DIR}/benchmark-day.json" ]]; then
        echo "## Day-over-day deltas (today vs yesterday)"
        echo ""
        echo "| Metric | Yesterday | Today | Delta |"
        echo "|---|---|---|---|"

        python3 - "${YESTERDAY_DIR}/benchmark-day.json" "${OUT_DIR}/benchmark-day.json" <<'PY'
import json, sys
keys = [
    ("total_events", "Total events"),
    ("blocked", "Blocked"),
    ("warn", "Warn"),
    ("shadow_blocked", "Shadow blocked"),
    ("fail_open", "Fail-open"),
    ("allowed", "Allowed"),
    ("allowed_via_override", "Allowed via override"),
    ("scope_creep_catches", "Scope-creep catches"),
    ("retry_after_block", "Retry after block"),
    ("false_positive_proxy", "False-positive proxy"),
    ("token_cost_proxy", "Token-cost proxy"),
    ("median_latency_ms", "Median latency ms"),
    ("p95_latency_ms", "p95 latency ms"),
]
prev = json.load(open(sys.argv[1]))
curr = json.load(open(sys.argv[2]))
for k, label in keys:
    p = prev.get(k)
    c = curr.get(k)
    if isinstance(p, (int, float)) and isinstance(c, (int, float)):
        delta = c - p
        print(f"| {label} | {p} | {c} | {delta:+.4g} |")
PY
    else
        echo "## Day-over-day comparison"
        echo ""
        echo "No previous-day benchmark found at ${YESTERDAY_DIR}/benchmark-day.json."
    fi

    echo ""
    echo "## 7-day snapshot"
    echo ""
    echo "See ${OUT_DIR}/benchmark-week.md for the trailing-week view."
    echo ""
    echo "_Generated by reasoning-core daily benchmark service. Audit proxies are operational diagnostics, not causal quality measures._"
} > "${TREND_MD}"

# Atomically update the latest symlink.
ln -sfn "${OUT_DIR}" "${LATEST_LINK}"

echo "[rc-daily-benchmark] wrote ${TREND_MD}"
echo "[rc-daily-benchmark] latest -> ${LATEST_LINK}"
